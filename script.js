function readImg(file){
  return new Promise((res,rej)=>{
    if(!file||!/^image\//.test(file.type)||file.size>25*1024*1024){rej();return}
    const url=URL.createObjectURL(file),im=new Image();
    im.onload=()=>{
      try{
        if(!im.naturalWidth||!im.naturalHeight)throw 0;
        const k=Math.min(1,1024/Math.max(im.naturalWidth,im.naturalHeight)),w=Math.round(im.naturalWidth*k),h=Math.round(im.naturalHeight*k);
        const cv=document.createElement('canvas'),cx=cv.getContext('2d');
        cv.width=w;cv.height=h;cx.fillStyle='#fff';cx.fillRect(0,0,w,h);cx.drawImage(im,0,0,w,h);
        const d=cv.toDataURL('image/jpeg',.72);
        URL.revokeObjectURL(url);
        okImg(d)?res(d):rej();
      }catch(e){URL.revokeObjectURL(url);rej()}
    };
    im.onerror=()=>{URL.revokeObjectURL(url);rej()};
    im.src=url;
  });
}
